_RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

def _gf28_multiply(a: int, b: int) -> int:
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        high_bit = a & 0x80
        a = (a << 1) & 0xFF
        if high_bit:
            a ^= 0x1b
        b >>= 1
    return p

class _EncryptionState:
    def apply_inv_sub_bytes(self):
        for r in range(4):
            for c in range(4):
                self.state[r][c] = _INV_SBOX[self.state[r][c]]

    def apply_inv_shift_rows(self):
        self.state[1] = self.state[1][-1:] + self.state[1][:-1]
        self.state[2] = self.state[2][-2:] + self.state[2][:-2]
        self.state[3] = self.state[3][-3:] + self.state[3][:-3]

    def apply_inv_mix_columns(self):
        for col in range(4):
            temp = [self.state[i][col] for i in range(4)]
            self.state[0][col] = _gf28_multiply(temp[0], 0x0e) ^ _gf28_multiply(temp[1], 0x0b) ^ \
                                _gf28_multiply(temp[2], 0x0d) ^ _gf28_multiply(temp[3], 0x09)
            self.state[1][col] = _gf28_multiply(temp[0], 0x09) ^ _gf28_multiply(temp[1], 0x0e) ^ \
                                _gf28_multiply(temp[2], 0x0b) ^ _gf28_multiply(temp[3], 0x0d)
            self.state[2][col] = _gf28_multiply(temp[0], 0x0d) ^ _gf28_multiply(temp[1], 0x09) ^ \
                                _gf28_multiply(temp[2], 0x0e) ^ _gf28_multiply(temp[3], 0x0b)
            self.state[3][col] = _gf28_multiply(temp[0], 0x0b) ^ _gf28_multiply(temp[1], 0x0d) ^ \
                                _gf28_multiply(temp[2], 0x09) ^ _gf28_multiply(temp[3], 0x0e)

    
    def __init__(self, input_bytes: bytes):
        self.state = [[0] * 4 for _ in range(4)]
        for col in range(4):
            for row in range(4):
                self.state[row][col] = input_bytes[row + 4 * col]

    def get_block(self) -> bytearray:
        output = bytearray(16)
        for col in range(4):
            for row in range(4):
                output[row + 4 * col] = self.state[row][col]
        return output

    def apply_sub_bytes(self):
        for r in range(4):
            for c in range(4):
                self.state[r][c] = _SBOX[self.state[r][c]]

    def apply_shift_rows(self):
        self.state[1] = self.state[1][1:] + self.state[1][:1]
        self.state[2] = self.state[2][2:] + self.state[2][:2]
        self.state[3] = self.state[3][3:] + self.state[3][:3]

    def apply_mix_columns(self):
        for col in range(4):
            temp = [self.state[i][col] for i in range(4)]
            self.state[0][col] = _gf28_multiply(temp[0], 0x02) ^ _gf28_multiply(temp[1], 0x03) ^ temp[2] ^ temp[3]
            self.state[1][col] = temp[0] ^ _gf28_multiply(temp[1], 0x02) ^ _gf28_multiply(temp[2], 0x03) ^ temp[3]
            self.state[2][col] = temp[0] ^ temp[1] ^ _gf28_multiply(temp[2], 0x02) ^ _gf28_multiply(temp[3], 0x03)
            self.state[3][col] = _gf28_multiply(temp[0], 0x03) ^ temp[1] ^ temp[2] ^ _gf28_multiply(temp[3], 0x02)

    def apply_add_round_key(self, key: list):
        for col in range(4):
            for row in range(4):
                self.state[row][col] ^= key[row + 4 * col]


class _AES256Encryptor:
    def __init__(self, key: bytes):
        # В AES-256 14 раундов, значит нужно 15 раундовых ключей по 16 байт
        self.round_keys = [[0] * 16 for _ in range(15)]
        self._expand_key(key)

    def _expand_key(self, key: bytes):
        # В AES-256 ключ состоит из 8 слов (32 байта).
        # Всего нам нужно 60 слов (15 раундов * 4 слова).
        words = [[0, 0, 0, 0] for _ in range(60)]
        
        # Первые 8 слов — это сам исходный ключ
        for i in range(8):
            words[i] = [key[4*i], key[4*i+1], key[4*i+2], key[4*i+3]]

        # Генерируем остальные 52 слова
        for i in range(8, 60):
            temp = words[i-1][:]
            
            if i % 8 == 0:
                # Циклический сдвиг, подстановка и RCON для каждого 8-го слова
                temp = temp[1:] + temp[:1]
                temp = [_SBOX[b] for b in temp]
                temp[0] ^= _RCON[i // 8]
            elif i % 8 == 4:
                # В AES-256 для каждого 4-го слова внутри блока применяется дополнительная подстановка
                temp = [_SBOX[b] for b in temp]

            # XOR с словом, которое было 8 шагов назад
            for j in range(4):
                words[i][j] = words[i-8][j] ^ temp[j]

        # Упаковываем 60 слов в 15 раундовых ключей по 16 байт
        for r in range(15):
            for w in range(4):
                for b in range(4):
                    self.round_keys[r][w * 4 + b] = words[r * 4 + w][b]

    def process_block(self, in_block: bytes) -> bytearray:
        st = _EncryptionState(in_block)
        st.apply_add_round_key(self.round_keys[0])

        # В AES-256 14 раундов (13 полных + 1 финальный)
        for r in range(1, 14):
            st.apply_sub_bytes()
            st.apply_shift_rows()
            st.apply_mix_columns()
            st.apply_add_round_key(self.round_keys[r])

        st.apply_sub_bytes()
        st.apply_shift_rows()
        st.apply_add_round_key(self.round_keys[14]) # 15-й ключ

        return st.get_block()


def encrypt_aes256(plaintext: str, hex_key: str) -> str:
    # 1. Парсинг и проверка ключа (теперь ожидаем 64 hex-символа = 32 байта)
    clean_key = hex_key.replace(" ", "").lower()
    if len(clean_key) != 64:
        raise ValueError("Длина ключа должна быть ровно 64 hex-символа (32 байта).")
    
    try:
        key_bytes = bytes.fromhex(clean_key)
    except ValueError:
        raise ValueError("Ключ содержит недопустимые hex-символы.")

    # 2. Инициализация шифратора
    encryptor = _AES256Encryptor(key_bytes)

    # 3. Подготовка и паддинг (PKCS#7)
    if isinstance(plaintext, str):
        pt_bytes = plaintext.encode('utf-8')
    else:
        pt_bytes = plaintext
    pad_len = 16 - (len(pt_bytes) % 16)
    padded_data = pt_bytes + bytes([pad_len] * pad_len)

    # 4. Поблочное шифрование
    cipher_bytes = bytearray()
    for i in range(0, len(padded_data), 16):
        block = padded_data[i:i + 16]
        cipher_bytes.extend(encryptor.process_block(block))

    # 5. Возврат результата
    return cipher_bytes.hex()

class _AES256Decryptor:
    def __init__(self, key: bytes):
        enc = _AES256Encryptor(key)
        self.round_keys = enc.round_keys

    def process_block(self, in_block: bytes) -> bytearray:
        st = _EncryptionState(in_block)
        
        # Начинаем с конца: AddRoundKey с 14-м ключом
        st.apply_add_round_key(self.round_keys[14])

        # 13 обратных раундов
        for r in range(13, 0, -1):
            st.apply_inv_shift_rows()
            st.apply_inv_sub_bytes()
            st.apply_add_round_key(self.round_keys[r])
            st.apply_inv_mix_columns()

        # Финальный обратный раунд (без MixColumns)
        st.apply_inv_shift_rows()
        st.apply_inv_sub_bytes()
        st.apply_add_round_key(self.round_keys[0])

        return st.get_block()

def decrypt_aes256(ciphertext_hex: str, hex_key: str) -> str:
    clean_key = hex_key.replace(" ", "").lower()
    key_bytes = bytes.fromhex(clean_key)
    cipher_bytes = bytes.fromhex(ciphertext_hex)
    
    decryptor = _AES256Decryptor(key_bytes)
    
    decrypted_data = bytearray()
    for i in range(0, len(cipher_bytes), 16):
        block = cipher_bytes[i:i + 16]
        decrypted_data.extend(decryptor.process_block(block))
    # Снимаем PKCS#7 паддинг
    pad_len = decrypted_data[-1]
    # Простая проверка на корректность паддинга
    if pad_len > 16:
        raise ValueError("Неверный пароль или поврежденные данные (ошибка паддинга).")
    
    return decrypted_data[:-pad_len].decode('utf-8')
